
public class E04_Operator2 {
	
	public static void main(String[] arges) {
		int n= 10;
		
		n += 2; //n = n + 2;
		System.out.println(n);
		n -= 2; //n = n - 2;
		System.out.println(n);
		n *= 2; //n = n * 2;
		System.out.println(n);
		n /= 2; //n = n / 2;
		System.out.println(n);
		n %= 2; //n = n % 2;
		System.out.println(n);
	}
}